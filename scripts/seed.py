import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SETUP_DOC = "docs/data-setup.md" 

REQUIRED_FILES = [
    "data/raw/fraudTrain.csv",
    "data/raw/fraudTest.csv",
]

POLICY_DIR = "data/policies"

GENERATED_FILES = [
    "data/processed/fraudTrain_features.csv",
]

def check_file(relative_path):
    if (ROOT/ relative_path).is_file():
        print(f" [OK]   {relative_path}")
        return True
    print(f"   [MISSING]  {relative_path}")
    return False


def check_policies():
    folder = ROOT / POLICY_DIR
    pdfs = list(folder.glob("*.pdf")) if folder.is_dir() else[]
    if pdfs:
        print(f"  [OK]    {POLICY_DIR}/comtains {len(pdfs)} PDF file(s)")
        return True
    print(f"    [MISSING]    {POLICY_DIR}/ has no PDF files")
    return False


def main():
    print("Checking AEGIS data files...\n")

    print("Required:")
    all_ok = True

    for path in REQUIRED_FILES:
        if not check_file(path):
            all_ok = False
        if not check_policies():
            all_ok = False

    print("\n Generated by notebooks (optional for now):")
    for path in GENERATED_FILES:
        if not (ROOT / path).is_file():
            print(f"  [NOT YET] {path}  (run notebooks/02-feature-engineering.ipynb)")
        else:
            print(f"  [OK]      {path}")

    print()
    if all_ok:
        print("All required data is in place.")
        return 0


    print(f"Some required files are missing. See in {SETUP_DOC} for where to get them.")

    return 1

if __name__ == '__main__':
    sys.exit(main())